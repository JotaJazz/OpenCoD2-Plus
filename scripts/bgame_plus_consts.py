#!/usr/bin/env python3
"""Writes the constants of CoD2rev-Plus's bgame for the engine's.

    python3 scripts/bgame_plus_consts.py [--cxx c++] [--check]

The engine's bgame (src/PC/bgame) follows CoD2rev-Plus's (src/bgame) line by
line, but cannot include its headers (their types clash with the engine's).
This compiles a program with CoD2rev-Plus's headers, once for each protocol,
that prints the value of each name in test/bgame_plus_consts.txt, and writes
them as #defines to src/PC/bgame/bg_plus_consts.h; a name whose value
differs between 1.0 and 1.3 is an error. With --check it only compares the
header with what it would write.
"""
import argparse, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = os.path.join(ROOT, 'test', 'bgame_plus_consts.txt')
HEADER = os.path.join(ROOT, 'src', 'PC', 'bgame', 'bg_plus_consts.h')
INCLUDES = ['qcommon/qcommon.h', 'bgame/bg_public.h', 'game/g_shared.h']


def load(path):
    with open(path) as f:
        return [l.strip() for l in f if l.strip() and not l.startswith('#')]


def values(cxx, names, protocol, tmp):
    src = os.path.join(tmp, 'consts.cpp')
    with open(src, 'w') as f:
        for inc in INCLUDES:
            f.write(f'#include "{os.path.join(ROOT, "src", inc)}"\n')
        f.write('#include <stdio.h>\nint main()\n{\n')
        for n in names:
            f.write(f'\tprintf("%s %.9g\\n", "{n}", (double)({n}));\n')
        f.write('\treturn 0;\n}\n')
    exe = os.path.join(tmp, f'consts{protocol}')
    subprocess.run([cxx, '-m32', '-std=gnu++17', '-w', '-DLISTEN_SERVER', f'-DPROTOCOL_VERSION={protocol}',
                    '-I', os.path.join(ROOT, 'src'), '-I', os.path.join(ROOT, 'src', 'headers'), '-I', ROOT,
                    '-include', os.path.join(ROOT, 'src', 'headers', 'glibc_compat.h'),
                    '-o', exe, src, '-Wl,--unresolved-symbols=ignore-all'], check=True)
    out = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    return dict(line.split() for line in out.splitlines())


def header(names, vals):
    lines = ['/* Generated by scripts/bgame_plus_consts.py from test/bgame_plus_consts.txt; do not edit.',
             ' * The values of CoD2rev-Plus\'s bgame constants (the same in 1.0 and 1.3), for',
             ' * the engine\'s bgame, which follows its code. */',
             '#ifndef COD2_BG_PLUS_CONSTS_H', '#define COD2_BG_PLUS_CONSTS_H', '']
    for n in names:
        lines += [f'#ifndef {n}', f'#define {n} {vals[n]}', '#endif']
    return '\n'.join(lines + ['', '#endif', ''])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--cxx', default='c++')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    names = load(NAMES)
    with tempfile.TemporaryDirectory() as tmp:
        v13 = values(args.cxx, names, 118, tmp)
        v10 = values(args.cxx, names, 115, tmp)
    differ = [n for n in names if v13[n] != v10[n]]
    if differ:
        print('differ between 1.0 and 1.3: ' + ', '.join(differ))
        return 1
    text = header(names, v13)
    if args.check:
        same = os.path.exists(HEADER) and open(HEADER).read() == text
        print('bg_plus_consts.h is ' + ('current' if same else 'stale'))
        return 0 if same else 1
    with open(HEADER, 'w') as f:
        f.write(text)
    print(f'{len(names)} constants')
    return 0


if __name__ == '__main__':
    sys.exit(main())
