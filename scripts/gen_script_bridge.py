#!/usr/bin/env python3
"""Generates the C/C++ bridge between the engine and CoD2rev-Plus's script VM.

    python3 scripts/gen_script_bridge.py [--build build/check-linux]

The engine calls the VM by C names; CoD2rev-Plus's src/script defines C++
functions (some overloaded) and calls engine functions by C++ names. Reading
the cod2_plus_script objects of a build configured with COD2_PLUS_SCRIPT=ON,
this writes:

- src/compat/script_exports.cpp: for each name in test/script_interface.txt,
  an extern "C" thunk whose symbol is the C name (an __asm__ label) and which
  calls the C++ function.
- src/compat/script_imports.cpp: for each C++ engine function the VM needs, a
  C++ definition that calls the engine's C symbol. Variadic ones format into
  a 4096-byte buffer and pass it on as "%s".

Return types come from decltype on the real CoD2rev-Plus declarations, so the
compiler checks every thunk against them.
"""
import argparse, glob, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Overloaded names the engine calls: the parameter list it means.
OVERLOADS = {
    'AddRefToValue': ['int', 'VariableUnion'],
    'RemoveRefToValue': ['int', 'VariableUnion'],
}

# Engine functions that take more arguments here than CoD2rev-Plus passes:
# (extra C parameter types, the values passed). src/PC/script passed 10.
EXTRA_ARGS = {
    'FS_ListFiles': (['int'], ['10']),
    'FS_FreeFileList': (['int'], ['10']),
}

# Engine functions with another name in this repo.
RENAMED = {
    'Hunk_ClearTempMemoryHighInternal': 'Hunk_ClearTempMemoryHigh',
}

# Functions the VM needs that this engine does not have; they are written by
# hand in src/compat/script_missing.cpp.
PROVIDED = {'Hunk_AllocXAnimTreePrecache', 'Q_rint', 'Q_vsnprintf', 'Sys_UnimplementedFunctionInternal',
            'VectorCompare'}

# Exports the engine calls with the client binary's script system id first
# ('sys'), which CoD2rev-Plus's single-system VM does not take. The other
# such functions only gain an ignored trailing argument; these two change
# meaning, so their thunks are written out (as src/PC/script behaved).
EXPORT_CUSTOM = {
    'Scr_FreeScripts': '''extern "C" void cod2x_Scr_FreeScripts(int sys) __asm__(COD2_SYM("Scr_FreeScripts"));
void cod2x_Scr_FreeScripts(int sys)
{
    // src/PC/script freed the scripts only for system 0; G_InitGame passes 1
    // right after loading them, which only ends the loading.
    if (sys == 0) {
        Scr_FreeScripts();
        return;
    }
    if (scrCompilePub.script_loading) {
        scrCompilePub.script_loading = 0;
        Scr_EndLoadScripts();
    }
    if (scrAnimPub.animtree_loading) {
        scrAnimPub.animtree_loading = 0;
        Scr_EndLoadAnimTrees();
    }
}
''',
    'Scr_ShutdownSystem': '''extern "C" void cod2x_Scr_ShutdownSystem(int sys, int bComplete) __asm__(COD2_SYM("Scr_ShutdownSystem"));
void cod2x_Scr_ShutdownSystem(int sys, int bComplete)
{
    (void)sys;  // ignored by src/PC/script too
    Scr_ShutdownSystem(bComplete);
}
''',
}

HEADER = '''// Generated by scripts/gen_script_bridge.py from CoD2rev-Plus's src/script; do not edit.
#include "../qcommon/qcommon.h"
#include "../script/script_public.h"
#include "script_bridge.h"
#include "script_decls.h"
'''


def split_params(text):
    """The top-level comma-separated parameter types of a demangled signature."""
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch in '(<[':
            depth += 1
        elif ch in ')>]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def named(ty, i):
    """'type aN', with the name inside a function pointer declarator."""
    if ty == '...':
        return '...'
    if '(*)' in ty:
        return ty.replace('(*)', f'(*a{i})', 1)
    return f'{ty} a{i}'


def fixed(params):
    return [p for p in params if p != '...']


def ret_type(name, params):
    return f'decltype({name}(' + ', '.join(f'std::declval<{p}>()' for p in fixed(params)) + '))'


def export_thunk(name, params):
    sig = ', '.join(named(p, i) for i, p in enumerate(params))
    args = ', '.join(f'a{i}' for i in range(len(fixed(params))))
    r = ret_type(name, params)
    return (f'extern "C" {r} cod2x_{name}({sig}) __asm__(COD2_SYM("{name}"));\n'
            f'{r} cod2x_{name}({sig}) {{ return {name}({args}); }}\n')


def import_thunk(name, params):
    sig = ', '.join(named(p, i) for i, p in enumerate(params))
    n = len(fixed(params))
    r = ret_type(name, params)
    extra_types, extra_values = EXTRA_ARGS.get(name, ([], []))
    csig = ', '.join([named(p, i) for i, p in enumerate(params)] +
                     [named(t, n + i) for i, t in enumerate(extra_types)])
    decl = f'extern "C" {r} cod2c_{name}({csig}) __asm__(COD2_SYM("{RENAMED.get(name, name)}"));\n'
    if '...' not in params:
        args = ', '.join([f'a{i}' for i in range(n)] + extra_values)
        return decl + f'{r} {name}({sig}) {{ return cod2c_{name}({args}); }}\n'
    fmt = f'a{n - 1}'
    before = ''.join(f'a{i}, ' for i in range(n - 1))
    return decl + (f'{r} {name}({sig})\n{{\n'
                   f'    char buf[4096];\n    va_list ap;\n    va_start(ap, {fmt});\n'
                   f'    vsnprintf(buf, sizeof(buf), {fmt}, ap);\n    va_end(ap);\n'
                   f'    return cod2c_{name}({before}"%s", buf);\n}}\n')


def choose_overload(name, signatures):
    """The parameter types of the signature the engine means for name."""
    candidates = [split_params(s[s.index('(') + 1:s.rindex(')')]) for s in signatures]
    if len(candidates) == 1:
        return candidates[0]
    want = OVERLOADS.get(name)
    if want is None or want not in candidates:
        sys.exit(f'{name} is overloaded ({signatures}); add it to OVERLOADS')
    return want


def demangle(symbols):
    out = subprocess.run(['c++filt'], input='\n'.join(symbols), capture_output=True, text=True).stdout
    return out.split('\n')[:len(symbols)]


def nm(args, objects):
    out = subprocess.run(['nm'] + args + objects, capture_output=True, text=True).stdout
    return [line.split()[-1] for line in out.splitlines() if line.strip() and not line.endswith(':')]


def signatures(mangled):
    """{name: [demangled signature, ...]} for the C++ function symbols."""
    sigs = {}
    for m, d in zip(mangled, demangle(mangled)):
        if m.startswith('_Z') and '(' in d and '::' not in d.split('(')[0]:
            sigs.setdefault(d.split('(')[0], []).append(d)
    return sigs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--build', default=os.path.join(ROOT, 'build', 'check-linux'))
    args = ap.parse_args()

    objects = sorted(glob.glob(os.path.join(args.build, 'CMakeFiles', 'cod2_plus_script.dir', 'src', 'script', '*.o')))
    if not objects:
        sys.exit('no cod2_plus_script objects: configure the build with -DCOD2_PLUS_SCRIPT=ON and build it')
    defined = set(nm(['-g', '--defined-only'], objects))
    undefined = sorted(set(nm(['-u'], objects)) - defined)
    exports = signatures(sorted(defined))
    imports = signatures([u for u in undefined if u.startswith('_Z')])

    with open(os.path.join(ROOT, 'test', 'script_interface.txt')) as f:
        interface = [l.strip() for l in f if l.strip() and not l.startswith('#')]

    out = [HEADER]
    missing = []
    for name in interface:
        if name in EXPORT_CUSTOM:
            out.append(EXPORT_CUSTOM[name])
        elif name in exports:
            out.append(export_thunk(name, choose_overload(name, exports[name])))
        elif name not in defined:
            missing.append(name)
    with open(os.path.join(ROOT, 'src', 'compat', 'script_exports.cpp'), 'w') as f:
        f.write('\n'.join(out))

    out = [HEADER]
    for name in sorted(set(imports) - PROVIDED):
        out.append(import_thunk(name, choose_overload(name, imports[name])))
    with open(os.path.join(ROOT, 'src', 'compat', 'script_imports.cpp'), 'w') as f:
        f.write('\n'.join(out))

    print(f'{len(interface) - len(missing)} exports, {len(imports)} imports')
    if missing:
        print('in test/script_interface.txt but not defined by src/script: ' + ' '.join(missing))
    return 0


if __name__ == '__main__':
    sys.exit(main())
