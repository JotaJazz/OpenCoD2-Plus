#!/usr/bin/env python3
"""Writes the eng_ names of the engine's bgame globals.

    python3 scripts/bgame_names.py

In the client the engine's bgame (for cgame) and CoD2rev-Plus's (for the
local server) both run, and they name some globals alike. For each name in
test/engine_bgame_names.txt this writes:

- src/headers/engine_bgame_names.h: '#define name eng_name', which
  common_types.h includes, so every C source of the engine (the bgame, cgame,
  the blobs and their imp_ pointers) uses the eng_ name;
- src/compat/server_bgame_names.cpp: a placeholder for each eng_ name in the
  dedicated server, which leaves the engine's bgame and the blobs' copies out
  but still links the imp_ pointers that take their addresses.

The MinGW blobs (.win.S) spell the labels themselves; they are renamed once
with --rename-asm FILE.
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PREFIX = 'eng_'


def load(path):
    with open(path) as f:
        return [l.strip() for l in f if l.strip() and not l.startswith('#')]


def header(names):
    lines = ['/* Generated by scripts/bgame_names.py from test/engine_bgame_names.txt; do not edit.',
             ' * The engine\'s bgame globals that CoD2rev-Plus\'s code also defines, under',
             ' * their own names, so that both bgames can run in the client. */',
             '#ifndef COD2_ENGINE_BGAME_NAMES_H', '#define COD2_ENGINE_BGAME_NAMES_H', '']
    lines += [f'#define {n} {PREFIX}{n}' for n in names]
    return '\n'.join(lines + ['', '#endif', ''])


def placeholders(names):
    lines = ['// Generated by scripts/bgame_names.py from test/engine_bgame_names.txt; do not edit.',
             '// The dedicated server links no engine bgame, but the imp_ pointers of',
             '// import_pointers_native.c still take these addresses; nothing reads them.',
             'extern "C" {', '']
    lines += [f'char {PREFIX}{n}[4];' for n in names]
    return '\n'.join(lines + ['', '}', ''])


def rename_asm(text, names):
    """The .S labels and references of names (with the C underscore), renamed."""
    pattern = re.compile(r'\b_(' + '|'.join(map(re.escape, names)) + r')\b')
    return pattern.sub(lambda m: '_' + PREFIX + m.group(1), text)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--rename-asm', metavar='FILE', action='append', default=[])
    args = ap.parse_args()
    names = load(os.path.join(ROOT, 'test', 'engine_bgame_names.txt'))
    with open(os.path.join(ROOT, 'src', 'headers', 'engine_bgame_names.h'), 'w') as f:
        f.write(header(names))
    with open(os.path.join(ROOT, 'src', 'compat', 'server_bgame_names.cpp'), 'w') as f:
        f.write(placeholders(names))
    for path in args.rename_asm:
        with open(path) as f:
            text = f.read()
        with open(path, 'w') as f:
            f.write(rename_asm(text, names))
    print(f'{len(names)} names')
    return 0


if __name__ == '__main__':
    sys.exit(main())
